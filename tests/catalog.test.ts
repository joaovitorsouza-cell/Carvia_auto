import assert from 'node:assert/strict';
import {validateProduct} from '../lib/product-validation';
import {previewImport} from '../lib/import-products';
import {blankVehicleFilter,productMatchesVehicle,parseVehicles} from '../lib/vehicles';
import {quoteMessage} from '../lib/quote';
const p={name:'Filtro',brand:'Marca',code:'001',category:'Filtro de óleo',price:1290,stock:3,minStock:2,active:true,kind:'filter',images:['https://example.com/a.jpg','https://example.com/b.jpg'],vehicles:parseVehicles('Marca|Modelo|2010-2015|1.0'),manufacturerCode:'FAB001'};
assert.equal(validateProduct(p).images.length,2);
for(const wrong of [{price:0},{stock:-1},{minStock:1.5},{images:['javascript:alert(1)']},{images:Array(9).fill('https://example.com/a')},{vehicles:[{make:'X',model:'Y',yearFrom:2024,yearTo:2020,engine:'1.0'}]}])assert.throws(()=>validateProduct({...p,...wrong}));
assert(productMatchesVehicle(p.vehicles,{...blankVehicleFilter,make:'marca',year:'2015'}));
assert(!productMatchesVehicle(p.vehicles,{...blankVehicleFilter,year:'2016'}));
assert(!productMatchesVehicle([],{...blankVehicleFilter,engine:'1.0'}));
const mixed=[...p.vehicles,{make:'Outra',model:'Carro',yearFrom:2020,yearTo:2024,engine:'2.0'}];assert(!productMatchesVehicle(mixed,{make:'Marca',model:'',year:'2024',engine:'2.0'}));
const r={codigo:'001',nome:'Filtro',categoria:'Filtros',preco:'12,90',estoque:'3',veiculos:'Marca|Modelo|2010-2015|1.0'};
assert.equal(previewImport([r],[],'skip')[0].data?.price,1290);
assert.equal(previewImport([r],[{id:'p',code:'001',revision:2}],'skip')[0].action,'Ignorar');
assert.equal(previewImport([r],[{id:'p',code:'001',revision:2}],'update')[0].revision,2);
assert(previewImport([r,r],[],'skip')[1].error);
assert(previewImport([{...r,estoque:'1.2'}],[],'skip')[0].error);
assert(previewImport([{...r,preco:''}],[],'skip')[0].error);
const message=quoteMessage([{...p,id:'p',description:''}],{p:2},true);assert(message.includes('Código: 001'));assert(message.includes('Quantidade: 2'));assert(message.includes('DEMONSTRAÇÃO'));
console.log('Filtros, validações, prévia de importação e orçamento: OK');
